namespace DocumentRecognition.Core.Enums
{
    /// <summary>
    /// Тип области результата распознавания.
    /// Используется для отрисовки подсветки и выбора стиля/приоритета при наведении.
    /// </summary>
    public enum RecognitionRegionKind
    {
        /// <summary>
        /// Блок разметки чертежа (основная надпись, технические требования, таблицы и т.п.).
        /// </summary>
        LayoutBlock = 0,

        /// <summary>
        /// Ячейка шаблонной сетки основной надписи (ГОСТ 2.104-68).
        /// </summary>
        TitleBlockCell = 1,

        /// <summary>
        /// Строка, распознанная OCR (внутри основной надписи или технических требований).
        /// </summary>
        OcrLine = 2,

        /// <summary>
        /// Ячейка таблицы, найденная детектором таблиц (без распознанного текста).
        /// </summary>
        TableCell = 3
    }
}
